package dev.murmr.app.hid

/** Report ID used for keyboard input reports. Must match the descriptor below. */
const val REPORT_ID_KEYBOARD = 1

/**
 * Standard USB/Bluetooth boot-protocol keyboard report descriptor.
 *
 * Input report (8 bytes, after the report ID):
 *   byte 0    modifier bitmask (bit 0 = Left Ctrl, bit 1 = Left Shift, ...)
 *   byte 1    reserved
 *   bytes 2-7 up to six concurrently pressed key usages (HID Usage Page 0x07)
 *
 * Output report (1 byte): keyboard LEDs (Num/Caps/Scroll lock...). We ignore it.
 */
val KEYBOARD_REPORT_DESCRIPTOR: ByteArray = intArrayOf(
    0x05, 0x01,        // Usage Page (Generic Desktop)
    0x09, 0x06,        // Usage (Keyboard)
    0xA1, 0x01,        // Collection (Application)
    0x85, REPORT_ID_KEYBOARD, // Report ID
    0x05, 0x07,        //   Usage Page (Keyboard/Keypad)
    0x19, 0xE0,        //   Usage Minimum (Left Control)
    0x29, 0xE7,        //   Usage Maximum (Right GUI)
    0x15, 0x00,        //   Logical Minimum (0)
    0x25, 0x01,        //   Logical Maximum (1)
    0x75, 0x01,        //   Report Size (1)
    0x95, 0x08,        //   Report Count (8)
    0x81, 0x02,        //   Input (Data, Variable, Absolute)  -- modifier byte
    0x95, 0x01,        //   Report Count (1)
    0x75, 0x08,        //   Report Size (8)
    0x81, 0x01,        //   Input (Constant)                  -- reserved byte
    0x95, 0x05,        //   Report Count (5)
    0x75, 0x01,        //   Report Size (1)
    0x05, 0x08,        //   Usage Page (LEDs)
    0x19, 0x01,        //   Usage Minimum (Num Lock)
    0x29, 0x05,        //   Usage Maximum (Kana)
    0x91, 0x02,        //   Output (Data, Variable, Absolute) -- LED bits
    0x95, 0x01,        //   Report Count (1)
    0x75, 0x03,        //   Report Size (3)
    0x91, 0x01,        //   Output (Constant)                 -- LED padding
    0x95, 0x06,        //   Report Count (6)
    0x75, 0x08,        //   Report Size (8)
    0x15, 0x00,        //   Logical Minimum (0)
    0x25, 0x65,        //   Logical Maximum (101)
    0x05, 0x07,        //   Usage Page (Keyboard/Keypad)
    0x19, 0x00,        //   Usage Minimum (0)
    0x29, 0x65,        //   Usage Maximum (101)
    0x81, 0x00,        //   Input (Data, Array)               -- 6 key slots
    0xC0,              // End Collection
).map { it.toByte() }.toByteArray()
